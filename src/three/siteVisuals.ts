import type { LandmarkBiome } from '../types/citylit';

export interface SitePointLightSpec {
  readonly pos: readonly [number, number, number];
  readonly color: string;
  readonly intensity: number;
  readonly distance: number;
}

export interface SiteVisualProfile {
  /** Soft bounce fill color during daytime. */
  readonly bounceDay: string;
  /** Soft bounce fill color during dusk/night for shaded architectural relief. */
  readonly bounceNight: string;
  /** Directional rim backlight tint that separates landmark silhouettes from the sky. */
  readonly rimColor: string;
  /** Extra rim multiplier around 1.0 (0.85..1.25). */
  readonly rimBoost: number;
  /** Atmospheric sky dome zenith tint blended gently into weather sky. */
  readonly skyTopTint: string;
  /** Atmospheric sky dome horizon tint blended gently into weather horizon. */
  readonly skyHorizonTint: string;
  /** Stylized N8AO crevice shadow ink (deep tinted shadow instead of flat charcoal). */
  readonly aoShadowColor: string;
  /** Plinth frame accent in daylight theme. */
  readonly plinthRingDay: string;
  /** Plinth frame emissive accent in dark/night theme. */
  readonly plinthRingNight: string;
  /** AAA split-tone color grade & focal micro-clarity calibration. */
  readonly grade: {
    readonly contrast: number;
    readonly saturation: number;
    readonly shadowLift: number;
    readonly shadowTint: readonly [number, number, number];
    readonly highlightTint: readonly [number, number, number];
    readonly clarity: number;
    readonly nightLift: number;
  };
  /** Up to 2 pooled non-shadowing night point lights anchored to the hero site. */
  readonly nightLights: {
    readonly primary: SitePointLightSpec;
    readonly secondary?: SitePointLightSpec;
  };
}

export function normalizeSiteVisualKey(key: string): string {
  return key.replace(/[’‘`]/g, "'");
}

